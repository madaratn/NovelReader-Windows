import { test, expect } from '@playwright/test'
import { open, nav } from './helpers'

test('global search: live progress, default languages, grouped results, add in place', async ({ page }) => {
  await open(page, { library: [], slowSources: true })
  await page.locator('.qs-open').click().then(()=>page.locator('.qs-all').click())
  // Default languages = UI language (en) + English + Multi: 12 + 2 sources.
  await expect(page.locator('.langcount')).toHaveText('14 sources selected')
  await page.fill('.search-main input', 'shadow slave')
  await page.locator('.search-main button').click()
  await expect(page.locator('.search-main button')).toHaveText('Stop')
  await expect(page.locator('.searchstatus.running')).toContainText('Searching')
  await expect(page.locator('.searchstatus:not(.running)')).toContainText('Search finished: 14 sources checked.', { timeout: 15_000 })
  await expect(page.locator('.searchstatus')).toContainText('1 source did not answer.')
  expect(await page.evaluate(() => new Set((window as any).__calls.search).size)).toBe(14)
  await expect(page.locator('.resultcard h3')).toHaveText(['Shadow Slave', 'Shadow Slave Side Stories'])
  await expect(page.locator('.resultcard').first()).toContainText(/Found on \d+ sources/)
  await page.locator('.resultcard').first().getByRole('button', { name: '＋ Add', exact: true }).click()
  await expect(page.locator('.search-toast.ok')).toContainText('“Shadow Slave” was added to your library.')
  await expect(page.locator('.resultcard').first().locator('.inlib')).toBeVisible()
  await nav(page, 'Library')
  await expect(page.locator('.libcard h2')).toHaveText(['Shadow Slave'])
})

